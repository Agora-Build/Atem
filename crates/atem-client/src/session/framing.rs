//! Prompt framing that sender text can't imitate (delegated host-work
//! design, III.2).
//!
//! Every prompt Atem renders around sender text (host-work tasks, message
//! tasks, marks, screenshot lines, local tasks and result deliveries) is a
//! [`Prompt`]: lines of Atem's own, each starting with `[atem <tag>] ` and
//! built only from verified fields, and counted blocks holding the sender's
//! text. The [`Tag`] is drawn for every rendered prompt, after the sender's
//! text is fixed. The second line is the rule line ([`RULE`]).
//!
//! **Counted blocks.** `[atem <tag>] begin <what> (<n> bytes)`, the text,
//! `[atem <tag>] end <what>`. `n` counts the escaped text in bytes and fixes
//! the block's end; when that text doesn't end with a newline (an empty one
//! included) a newline Atem adds, not counted, comes before the end line.
//!
//! **The tag is the guarantee.** A line is Atem's only if it starts with this
//! prompt's tag, which nobody knows before the sender's text is fixed. The
//! escaping is the extra layer: it marks sender lines that look like Atem's
//! marker, earlier or guessed tags included, so an agent doesn't have to
//! compare tags to see them; it catches what the folding below catches and
//! nothing more.
//!
//! **Escaping** ([`escape`]): the text is cut into lines at every line break
//! ([`is_line_break`]), and a line that folds to Atem's marker gets a `|` in
//! front of it, right after its break. The folding ([`fold`]), in III.2's
//! order, works on a copy used only to decide:
//! 1. lines, as above;
//! 2. every character of General_Category Cf is dropped;
//! 3. NFKC;
//! 4. Unicode's default lowercase mapping;
//! 5. the UTS #39 confusables skeleton of step 4's output (NFD, Default
//!    Ignorable code points dropped, each character replaced by its
//!    prototype, NFD again);
//! 6. leading White_Space is skipped in step 4's and step 5's output; the
//!    line folds to the marker if the first starts with `[atem` or the second
//!    with the skeleton of `[atem` (`[atern`).
//!
//! Four readings are stricter than III.2's text, each escaping more lines,
//! never fewer (host-work v1 §4 "Rendering" records them):
//! - **Line breaks.** CR, VT, FF and NEL also end a line here. Host-work v1's
//!   text rule refuses them as control characters, so a valid task never
//!   has one; a caller that passes one anyway still gets its next line
//!   checked.
//! - **Escaping is reversible.** A line is escaped when its folded form
//!   *after the `|`s it starts with* starts with the marker, so a sender's
//!   `|[atem` becomes `||[atem`. Without it `[atem` and `|[atem` would both
//!   read `|[atem`, and nobody (an agent, [`Prompt::parse`]) could tell which
//!   the sender wrote. [`unescape`] removes exactly the `|` [`escape`] added.
//! - **The skeleton is UTS #39's own**, which drops Default_Ignorable code
//!   points (U+034F, variation selectors, Hangul fillers) that step 2 keeps
//!   because they aren't Cf.
//! - **A third form: the skeleton of the capitals.** Step 5 takes the
//!   skeleton after lowercasing, and the lowercase forms of most capital
//!   look-alikes in other scripts aren't listed as confusable with Latin
//!   (Cyrillic `Т` lowers to `т`, Greek `Μ` to `μ`). So the line is also
//!   skeletonized before lowercasing, then lowercased and skeletonized
//!   again, and compared with `[atern` the same way: `[АТЕМ`, `[ΑΤΕΜ`,
//!   `[ᎪᎢᎬᎷ` and `[ꓮꓔꓰꓟ` fold to the marker through it.
//!
//! All folding data is of one Unicode version ([`UNICODE_VERSION`], 18.0.0):
//! normalization, general categories and confusables from crates pinned to
//! it, and the default lowercase mapping and White_Space from tables
//! generated from its data files (`framing/unicode_data.rs`), not Rust's
//! own, which follow the toolchain. The lowercase mapping skips one rule of
//! Unicode's: Final_Sigma (a final `Σ` lowers to `ς`, else to `σ`; here
//! always `σ`). Neither `σ` nor `ς` folds to a character of the marker, so
//! the rule can't change a match (a test checks it).
