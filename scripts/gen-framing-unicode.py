#!/usr/bin/env python3
"""Generates crates/atem-client/src/session/framing/unicode_data.rs: the
Unicode 18.0.0 data the prompt framing's folding takes from no crate
(the default lowercase mapping and White_Space), so no step of the folding
depends on the Rust toolchain's own Unicode version.

Usage, from the repository's root (inputs are untrusted downloads: keep them
in their own directory and run with -I):

    mkdir -p /tmp/ucd-18
    (cd /tmp/ucd-18 && for f in UnicodeData SpecialCasing PropList; do
      curl -fsSLO "https://www.unicode.org/Public/18.0.0/ucd/$f.txt"; done)
    python3 -I scripts/gen-framing-unicode.py /tmp/ucd-18 \
      > crates/atem-client/src/session/framing/unicode_data.rs

The inputs must match the SHA-256 values below; a new Unicode version comes
with new framing vectors (designs/protocol/fixtures/host-work/).
"""
import hashlib
import os
import sys

VERSION = (18, 0, 0)
INPUTS = {
    "UnicodeData.txt": "0736451de439ae7baf1425136617da495e09ee5afbe6e394374db7009ea08950",
    "SpecialCasing.txt": "8538dea57c184f1ef3783885ea79677b10f6efa06423717157e63712f14d1ad2",
    "PropList.txt": "f438f532e8737bb8a2702126cdf9c4af5e357c58c7acf9d9eb2fc7c1a1d955d6",
}


def read(directory, name):
    data = open(os.path.join(directory, name), "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != INPUTS[name]:
        sys.exit(f"{name}: sha256 {digest}, expected {INPUTS[name]}")
    return data.decode("utf-8")


def lines(text):
    for line in text.split("\n"):
        line = line.split("#", 1)[0].strip()
        if line:
            yield [f.strip() for f in line.split(";")]


def main():
    directory = sys.argv[1]
    simple = {}
    for f in lines(read(directory, "UnicodeData.txt")):
        if f[13]:
            simple[int(f[0], 16)] = int(f[13], 16)
    # Unconditional full lowercase mappings that differ from the simple ones
    # (the default lowercase mapping; conditional ones aren't part of it but
    # Final_Sigma, see framing.rs).
    special = {}
    for f in lines(read(directory, "SpecialCasing.txt")):
        code, lower = int(f[0], 16), [int(x, 16) for x in f[1].split()]
        condition = f[4] if len(f) > 4 else ""
        if not condition and lower != [simple.get(code, code)]:
            special[code] = lower
    white = []
    for f in lines(read(directory, "PropList.txt")):
        if f[1] == "White_Space":
            a, _, b = f[0].partition("..")
            white.append((int(a, 16), int(b or a, 16)))
    white.sort()

    # Runs of equal deltas at a fixed step (1 or 2): the code points between
    # two entries of a run have no mapping, since the entries are consecutive
    # in code point order.
    runs = []
    for code in sorted(simple):
        delta = simple[code] - code
        if runs:
            first, last, step, d = runs[-1]
            gap = code - last
            if d == delta and (gap == step or (first == last and gap in (1, 2))):
                runs[-1] = (first, code, gap, d)
                continue
        runs.append((code, code, 1, delta))

    def lookup(code):
        for first, last, step, d in runs:
            if first <= code <= last and (code - first) % step == 0:
                return code + d
        return code

    for code in range(0x110000):
        if lookup(code) != simple.get(code, code):
            sys.exit(f"run table wrong at U+{code:04X}")

    out = []
    w = out.append
    w("//! Generated by `scripts/gen-framing-unicode.py` from Unicode "
      f"{VERSION[0]}.{VERSION[1]}.{VERSION[2]}; do not edit.")
    w("//!")
    for name, digest in INPUTS.items():
        w(f"//! - `{name}`: sha256 `{digest}`")
    w("")
    w("/// The Unicode version of these tables.")
    w(f"pub const VERSION: (u64, u64, u64) = ({VERSION[0]}, {VERSION[1]}, {VERSION[2]});")
    w("")
    w("/// White_Space (`PropList.txt`), as inclusive ranges.")
    w("pub const WHITE_SPACE: &[(char, char)] = &[")
    for a, b in white:
        w(f"    ('\\u{{{a:x}}}', '\\u{{{b:x}}}'),")
    w("];")
    w("")
    w("/// The simple lowercase mappings (`UnicodeData.txt` field 13) as runs")
    w("/// `(first, last, step, delta)`: every `step`-th code point from `first`")
    w("/// to `last` maps to itself plus `delta`; no other code point in a run's")
    w("/// range has a mapping.")
    w("pub const LOWERCASE: &[(u32, u32, u32, i32)] = &[")
    for first, last, step, d in runs:
        w(f"    (0x{first:x}, 0x{last:x}, {step}, {d}),")
    w("];")
    w("")
    w("/// The unconditional full lowercase mappings of `SpecialCasing.txt`")
    w("/// that differ from the simple ones.")
    w("pub const SPECIAL_LOWERCASE: &[(char, &[char])] = &[")
    for code, lower in sorted(special.items()):
        chars = ", ".join(f"'\\u{{{c:x}}}'" for c in lower)
        w(f"    ('\\u{{{code:x}}}', &[{chars}]),")
    w("];")
    print("\n".join(out))


main()
